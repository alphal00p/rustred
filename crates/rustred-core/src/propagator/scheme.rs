//! The Scheme lane (M5-R0 A1 spike, NOT merged): Forcer's FORCERD hand scheme of
//! a non-planar node, re-derived as a RustRed template lane on the Diamond-lane
//! model. RustRed stays the engine: Forcer supplies only the shape of the rules.
//!
//! - The node's presentation ([`PresentationKind::SchemeAdapted`]) has Forcer's
//!   momentum routing and Forcer's dot-product ISPs (`2 p2.p4`, `2 Q.p2`,
//!   `2 Q.p3` for no1, the normalisation `Z(n) 2^(n12+n13+n14)` of FORCERD),
//!   the lines in canonical order (`check_on_graph`). The census transports
//!   every other presentation onto it, as Forcer's `DotRewrite` does.
//! - Each rule is a polynomial relation `Sum_s r_s(d, n) I(n + s) = 0` on a
//!   domain of `n` (Forcer's pattern). [`SchemeTemplate::extract`] rebuilds it
//!   from the generator's own rows (`RowId::OrdinaryIbp`), shifted and weighted
//!   by a stored certificate `Sum lambda_{k,t}(d, n) Row_k(n + t)`, possibly
//!   with rules verified before it as further generators, and compares it with
//!   the relation exactly in `Q(d)[n]` on the domain. A rule without a
//!   certificate, or whose certificate does not rebuild it, is unverified: the
//!   step refuses it unless `RUSTRED_P_SCHEME_UNVERIFIED=1` (spike measurement).
//! - The step applies the FIRST matching rule in Forcer's order (loop 1: the
//!   B rules, then the n12, n14, n13 numerator rules; loop 2: dots in the line
//!   order 1, 11, 5, 2, 6, 3, 4, 7, 10, 9), weights `-r_s(n) / r_0(n)`. A child
//!   with a line at power <= 0 is a [`PStage::Route`] key (subsector); the
//!   corner is the owner's residual terminal.
//! - Order key: (numerator rank, -n12, -n14, line-power sum, the loop-2 line
//!   order): every same-owner child is strictly lower (checked in the step).
//!
//! Sign convention: RustRed slots are `D = mom.mom` with `q.q = -1`, i.e. minus
//! Forcer's Euclidean slots, so `I_RR(n) = (-1)^(Sum n) Z(n)` and a Forcer
//! coefficient at shift `s` takes the sign `(-1)^(Sum s)`; a certificate weight
//! at offset `t` takes `(-1)^(Sum t)`.
