//! The Scheme lane (M5 A1 schemes): Forcer's hand-chosen reduction schemes of
//! the custom nodes, ported into RustRed as data-driven template lanes. RustRed
//! stays the engine: Forcer supplies only the choice and the ORDER of the rules;
//! every rule is a combination of RustRed's own IBP rows, verified exactly.
//!
//! - A scheme is one JSON file (schema `rustred.p-scheme.v2`): the node's graph
//!   in Forcer's routing and ISP basis, an ORDERED rule list (the dispatch order:
//!   `first_valid` in the stored order, strictly followed, no re-sorting), the
//!   descent order key (`order`: lexicographic rows), per-rule metadata (`meta`:
//!   RHS terms, raised lines, rank change, eps-pivot flag, provenance) and the
//!   per-scheme provenance. The embedded schemes are [`EMBEDDED_SCHEMES`];
//!   `RUSTRED_P_SCHEME_DIR` (development) adds or replaces schemes from a
//!   directory of `*.json` files; `RUSTRED_P_SCHEMES` (`all`, `none` or a comma
//!   list) chooses which schemes the assembly uses (default: the files with
//!   `"default": true`). [`P_SCHEME_TEMPLATE_VERSION`] names the meaning of the
//!   embedded set.
//! - The node's presentation ([`PresentationKind::SchemeAdapted`]) has Forcer's
//!   momentum routing and Forcer's dot-product ISPs (with FORCERD's
//!   normalisation, e.g. `Z(n) 2^(n12+n13+n14)` for no1), the lines in canonical
//!   order (`check_on_graph`). The census transports every other presentation
//!   onto it, as Forcer's `DotRewrite` does: the ISP basis of the scheme is the
//!   owner's, whatever basis the inputs or the parent owners use.
//! - Each rule is a polynomial relation `Sum_s r_s(d, n) I(n + s) = 0` on a
//!   domain of `n` (Forcer's pattern). [`SchemeTemplate::extract`] rebuilds it
//!   from the generator's own rows (`RowId::OrdinaryIbp`), shifted and weighted
//!   by a stored certificate `Sum lambda_{k,t}(d, n) Row_k(n + t)`, possibly
//!   with rules verified before it as further generators, and compares it with
//!   the relation exactly in `Q(d)[n]` on the domain. A rule whose parametric
//!   certificate is too expensive may carry a `replay` record instead: the exact
//!   replay of the relation at numeric index points through an independent
//!   verified p library (examples/scheme_replay.rs), with mutation control. A
//!   rule with neither is unverified: the step refuses it unless
//!   `RUSTRED_P_SCHEME_UNVERIFIED=1`.
//! - Descent is proved statically at program build ([`SchemeTemplate::extract`]):
//!   on Apply keys (lines >= 1, ISPs <= 0) every order row is linear, so a
//!   same-owner child at shift `s` is lower iff the row differences at `s` are
//!   lexicographically negative; every term that can stay in the owner is
//!   checked once per rule (the witness), and the step re-checks every child.
//!
