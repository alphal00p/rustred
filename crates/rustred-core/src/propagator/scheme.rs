    /// `poly` with `n_slot = v` is identically zero (Forcer coordinates).
    fn vanishes(poly: &Poly, slot: usize, v: i64) -> bool {
        let mut sum: BTreeMap<Vec<u32>, (i128, i128)> = BTreeMap::new();
        for (exponents, num, den) in &poly.0 {
            let mut e = exponents.clone();
            let power = std::mem::take(&mut e[slot + 1]);
            let factor = i128::from(v).pow(power);
            let (n0, d0) = sum.get(&e).copied().unwrap_or((0, 1));
            let (n1, d1) = (i128::from(*num) * factor, i128::from(*den));
            sum.insert(e, (n0 * d1 + n1 * d0, d0 * d1));
        }
        sum.values().all(|(n, _)| *n == 0)
    }

    fn rows(scheme: &Scheme) -> Vec<Row> {
        (scheme.order.iter())
            .map(|row| match row {
                OrderRow::Rank => Row::Rank,
                OrderRow::LineSum => Row::LineSum,
                OrderRow::Linear { weights, when } => Row::Linear(weights.clone(), *when),
            })
            .collect()
    }

    fn witness(scheme: &Scheme, order: &[Row]) -> Result<usize, String> {
        let rules: Vec<WitnessRule<'_>> = (scheme.rules.iter())
            .filter(|rule| !rule.master)
            .map(|rule| WitnessRule {
                name: &rule.name,
                pattern: &rule.pattern,
                shifts: if rule.relation.is_empty() {
                    rule.raw.iter().map(|(s, _, _)| s.as_slice()).collect()
                } else {
                    (rule.relation.iter())
                        .filter(|(s, _)| s.iter().any(|&x| x != 0))
                        .map(|(s, _)| s.as_slice())
                        .collect()
                },
            })
            .collect();
        let live: Vec<&ParsedRule> = scheme.rules.iter().filter(|rule| !rule.master).collect();
        static_descent(
            &scheme.name,
            scheme.lines.len(),
            order,
            &rules,
            |r, t, slot, v| {
                let rule = live[r];
                Ok(if rule.relation.is_empty() {
                    vanishes(&rule.raw[t].1, slot, v)
                } else {
                    let nonzero: Vec<&Poly> = (rule.relation.iter())
                        .filter(|(s, _)| s.iter().any(|&x| x != 0))
                        .map(|(_, p)| p)
                        .collect();
                    vanishes(nonzero[t], slot, v)
                })
            },
        )
    }

    #[test]
    fn every_embedded_scheme_parses_with_a_valid_stored_order() {
        for (name, json) in EMBEDDED_SCHEMES {
            let scheme = parse_scheme(json).unwrap();
            assert_eq!(scheme.name, *name);
            assert!(!scheme.rules.is_empty() && !scheme.order.is_empty());
            let checked = witness(&scheme, &rows(&scheme)).unwrap();
            assert!(checked > 0, "{name}: no same-owner shift checked");
        }
    }

    #[test]
    fn a_reordered_order_key_fails_the_descent_witness() {
        let scheme = parse_scheme(EMBEDDED_SCHEMES[0].1).unwrap();
        let mut order = rows(&scheme);
        let first = order.remove(0);
        order.push(first);
        assert!(
            witness(&scheme, &order).is_err(),
            "the rank row moved last must break descent"
        );
        let mut order = rows(&scheme);
        order.truncate(1);
        assert!(
            witness(&scheme, &order).is_err(),
            "the rank row alone cannot order the scheme"
        );
    }

