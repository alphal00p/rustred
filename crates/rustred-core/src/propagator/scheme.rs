/// One slot condition of a Forcer pattern, `lo <= n <= hi`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct Cond {
    lo: i64,
    hi: i64,
}

impl Cond {
    fn parse(value: &serde_json::Value) -> Result<Self, String> {
        if let Some(v) = value.as_i64() {
            return Ok(Self { lo: v, hi: v });
        }
        let (lo, hi) = match value.as_str() {
            Some("pos") => (1, i64::MAX),
            Some("gt1") => (2, i64::MAX),
            Some("neg") => (i64::MIN, -1),
            Some("neg0") => (i64::MIN, 0),
            Some("any") => (i64::MIN, i64::MAX),
            _ => return Err(format!("pattern entry {value}")),
        };
        Ok(Self { lo, hi })
    }

    fn holds(self, n: i64) -> bool {
        self.lo <= n && n <= self.hi
    }

    fn fixed(self) -> Option<i64> {
        (self.lo == self.hi).then_some(self.lo)
    }

    /// `self + t` lies inside `outer` (infinite bounds stay infinite).
    fn shifted_inside(self, t: i64, outer: Self) -> bool {
        let move_bound = |b: i64| if b == i64::MIN || b == i64::MAX { b } else { b.saturating_add(t) };
        outer.lo <= move_bound(self.lo) && move_bound(self.hi) <= outer.hi
    }
}

/// A Forcer-convention polynomial in `(d, n_1..n_14)`.
struct Poly(Vec<(Vec<u32>, i64, i64)>);

impl Poly {
    fn parse(record: &PolyRecord) -> Result<Self, String> {
        let mut terms = Vec::with_capacity(record.len());
        for (exponents, value) in record {
            let (num, den) = match value.split_once('/') {
                Some((n, d)) => (n.parse::<i64>(), d.parse::<i64>()),
                None => (value.parse::<i64>(), Ok(1)),
            };
            let (num, den) = (num.map_err(|e| e.to_string())?, den.map_err(|e| e.to_string())?);
            terms.push((exponents.clone(), num, den));
        }
        Ok(Self(terms))
    }
}

struct ParsedRule {
    name: String,
    /// Forcer slot order.
    pattern: Vec<Cond>,
    master: bool,
    relation: Vec<(Vec<i64>, Poly)>,
    certificate: Option<Vec<(Generator, Vec<i64>, Poly)>>,
    raw: Vec<(Vec<i64>, Poly, Vec<(Poly, u32)>)>,
}

enum Generator {
    /// `(differentiated loop, contraction momentum)`.
    Row(usize, usize),
    Rule(String),
}

struct Scheme {
    name: String,
    loops: u8,
    topo: PTopo,
    key: GraphKey,
    lines: Vec<LineRecord>,
    isps: Vec<IspRecord>,
    verify_order: Vec<String>,
    rules: Vec<ParsedRule>,
}

fn parse_scheme(json: &str) -> Result<Scheme, String> {
    let file: SchemeFile = serde_json::from_str(json).map_err(|e| e.to_string())?;
    if file.schema != "rustred.p-scheme.v1" {
        return Err(format!("schema {}", file.schema));
    }
    let topo = PTopo::new(
        file.vertices,
        file.s,
        file.t,
        file.lines.iter().map(|line| (line.tail, line.head, 0)),
    );
    let (key, _) = canonical(&topo);
    let mut rules = Vec::with_capacity(file.rules.len());
    for record in &file.rules {
        let pattern = (record.pattern.iter())
            .map(Cond::parse)
            .collect::<Result<Vec<_>, _>>()?;
        let mut relation = Vec::new();
        for (shift, poly) in record.relation.iter().flatten() {
            relation.push((shift.clone(), Poly::parse(poly)?));
        }
        let certificate = match &record.certificate {
            None => None,
            Some(items) => {
                let mut out = Vec::with_capacity(items.len());
                for (kind, reference, shift, poly) in items {
                    let generator = match kind.as_str() {
                        "row" => {
                            let pair = reference.as_array().ok_or("row reference")?;
                            let i = pair.first().and_then(|v| v.as_u64()).ok_or("row i")? as usize;
                            let j = pair.get(1).and_then(|v| v.as_u64()).ok_or("row j")? as usize;
                            Generator::Row(i, j)
                        }
                        "rule" => Generator::Rule(
                            reference.as_str().ok_or("rule reference")?.to_owned(),
                        ),
                        other => return Err(format!("generator kind {other}")),
                    };
                    out.push((generator, shift.clone(), Poly::parse(poly)?));
                }
                Some(out)
            }
        };
        let mut raw = Vec::new();
        for (shift, num, dens) in record.terms.iter().flatten() {
            let mut factors = Vec::with_capacity(dens.len());
            for (den, power) in dens {
                factors.push((Poly::parse(den)?, *power));
            }
            raw.push((shift.clone(), Poly::parse(num)?, factors));
        }
        rules.push(ParsedRule {
            name: record.name.clone(),
            pattern,
            master: record.master,
            relation,
            certificate,
            raw,
        });
    }
    Ok(Scheme {
        name: file.scheme,
        loops: file.loops,
        topo,
        key,
        lines: file.lines,
        isps: file.isps,
        verify_order: file.verify_order,
        rules,
    })
}

fn scheme_no1() -> Result<&'static Scheme, PError> {
    static SCHEME: OnceLock<Result<Scheme, String>> = OnceLock::new();
    SCHEME
        .get_or_init(|| match std::env::var("RUSTRED_P_SCHEME_JSON") {
            // Spike only: a mutated copy for the verification's mutation test.
            Ok(path) => std::fs::read_to_string(&path)
                .map_err(|error| format!("{path}: {error}"))
                .and_then(|json| parse_scheme(&json)),
            Err(_) => parse_scheme(SCHEME_NO1_V1_JSON),
        })
        .as_ref()
        .map_err(|error| PError::MalformedLibrary(format!("embedded scheme no1: {error}")))
}

fn scheme_enabled() -> bool {
    std::env::var("RUSTRED_P_SCHEME").map_or(true, |value| value != "0")
}

/// The scheme of `node`, if one is embedded for its graph (and the lane is not
/// switched off with `RUSTRED_P_SCHEME=0`).
pub fn scheme_for(node: &NodeInfo) -> Option<SchemeRoles> {
    if !scheme_enabled() || node.eps_lines != 0 {
        return None;
    }
    let scheme = scheme_no1().ok()?;
    (node.loops == scheme.loops && node.key == scheme.key).then_some(SchemeRoles { scheme: 0 })
}

/// Forcer slot `a` (0-based, `0..14`) -> presentation slot, and the slots.
struct Layout {
    perm: Vec<usize>,
    slots: Vec<Slot>,
}

fn layout(scheme: &Scheme, graph: &PTopo) -> Result<Layout, PError> {
    let fail = |detail: String| PError::Contract(format!("scheme {}: {detail}", scheme.name));
    let (key, canon) = canonical(&scheme.topo);
    let (graph_key, _) = canonical(graph);
    if key != graph_key {
        return Err(fail("the node is not the scheme's graph".to_owned()));
    }
    let mapped = canon.apply(&scheme.topo);
    if mapped.lines != graph.lines || (mapped.s, mapped.t) != (graph.s.min(graph.t), graph.s.max(graph.t)) {
        return Err(fail("the canonical labelling differs from the node's".to_owned()));
    }
    let vm = &canon.vertex_map;
    let eps = if vm[usize::from(scheme.topo.s)] == graph.s {
        1
    } else if vm[usize::from(scheme.topo.s)] == graph.t {
        -1
    } else {
        return Err(fail("q does not enter at an external vertex".to_owned()));
    };
    let width = usize::from(scheme.loops) + 1;
    let lines = scheme.lines.len();
    let mut perm = vec![usize::MAX; lines + scheme.isps.len()];
    let mut slots: Vec<Option<Slot>> = vec![None; lines];
    for (a, line) in scheme.lines.iter().enumerate() {
        let c = usize::from(canon.line_map[a]);
        let (u, v, _) = graph.lines[c];
        let (tail, head) = (vm[usize::from(line.tail)], vm[usize::from(line.head)]);
        let sign = if (tail, head) == (u, v) {
            1
        } else if (head, tail) == (u, v) {
            -1
        } else {
            return Err(fail(format!("line {a} does not map onto line {c}")));
        };
        if line.momentum.len() != width {
            return Err(fail(format!("line {a} has {} momentum entries", line.momentum.len())));
        }
        let mut momentum: Vec<i64> = line.momentum.iter().map(|x| sign * x).collect();
        momentum[width - 1] *= eps;
        perm[a] = c;
        slots[c] = Some(Slot::Line(SlotLine {
            momentum,
            eps_units: 0,
        }));
    }
    let mut out: Vec<Slot> = slots
        .into_iter()
        .map(|slot| slot.ok_or_else(|| fail("a canonical line has no scheme line".to_owned())))
        .collect::<Result<_, _>>()?;
    for (index, isp) in scheme.isps.iter().enumerate() {
        let external = |row: &[i64]| {
            let mut row = row.to_vec();
            row[width - 1] *= eps;
            row
        };
        perm[lines + index] = lines + index;
        out.push(Slot::Isp(SlotIsp {
            left: external(&isp.left),
            right: external(&isp.right),
        }));
    }
    Ok(Layout { perm, slots: out })
}

/// The scheme-adapted presentation of `node`.
pub fn scheme_presentation(
    node: &NodeInfo,
    roles: &SchemeRoles,
    id: PresentationId,
    context: &CoefficientContext,
) -> Result<Presentation, PError> {
    if roles.scheme != 0 {
        return Err(PError::Contract(format!("unknown scheme {}", roles.scheme)));
    }
    let scheme = scheme_no1()?;
    let layout = layout(scheme, &node.topo)?;
    Presentation::from_slots(
        id,
        PresentationKind::SchemeAdapted,
        &format!("p_node_{}", node.key.to_hex()),
        node.loops,
        layout.slots,
        context,
        Some(NodeRef {
            index: NodeIndex(node.index),
            graph_key: Arc::clone(&node.key.0),
        }),
    )
}

/// One rule in presentation coordinates.
#[derive(Clone, Debug)]
pub struct SchemeRule {
    pub name: String,
    /// Presentation slot order.
    pattern: Vec<Cond>,
    pub master: bool,
    /// `(shift, r_s)`, the zero shift first.
    terms: Vec<(Vec<i64>, IndexedCoefficient)>,
    /// A rule without a relation: Forcer's `c_j` as `(shift, num, dens)`, signed.
    raw: Vec<(Vec<i64>, IndexedCoefficient, Vec<(IndexedCoefficient, u32)>)>,
    pub verified: bool,
}

/// The rules of one scheme on its presentation, each checked against the
/// generator's rows.
#[derive(Clone, Debug)]
pub struct SchemeTemplate {
    presentation: PresentationId,
    context: IndexedCoefficientContext,
    perm: Vec<usize>,
    rules: Vec<SchemeRule>,
}

/// `(-1)^(Sum s)`.
fn parity(shift: &[i64]) -> i64 {
    if shift.iter().sum::<i64>().rem_euclid(2) == 0 { 1 } else { -1 }
}

struct Builder<'a> {
    context: &'a IndexedCoefficientContext,
    base: &'a CoefficientContext,
    perm: &'a [usize],
    d: Coefficient,
}

impl Builder<'_> {
    fn rational(&self, num: i64, den: i64) -> Result<Coefficient, PError> {
        self.base
            .try_div(
                &self.base.integer(num),
                &self.base.integer(den),
                ExactAlgebraLimits::default(),
            )
            .map_err(exact)
    }

    /// `sign * poly` in presentation coordinates.
    fn poly(&self, poly: &Poly, sign: i64) -> Result<IndexedCoefficient, PError> {
        let limits = ExactAlgebraLimits::default();
        let mut total = self.context.zero();
        for (exponents, num, den) in &poly.0 {
            let mut constant = self.rational(sign * num, *den)?;
            for _ in 0..exponents[0] {
                constant = self.base.try_mul(&constant, &self.d, limits).map_err(exact)?;
            }
            let mut term = self.context.lift(&constant).map_err(indexed)?;
            for (variable, &power) in exponents.iter().enumerate().skip(1) {
                if power == 0 {
                    continue;
                }
                let index = self.context.index(self.perm[variable - 1]).map_err(indexed)?;
                for _ in 0..power {
                    term = self.context.mul(&term, &index).map_err(indexed)?;
                }
            }
            total = self.context.add(&total, &term).map_err(indexed)?;
        }
        Ok(total)
    }

    fn shift(&self, forcer: &[i64]) -> Vec<i64> {
        let mut out = vec![0; forcer.len()];
        for (a, &s) in forcer.iter().enumerate() {
            out[self.perm[a]] = s;
        }
        out
    }
}

impl SchemeTemplate {
    /// The rules of the scheme on `p` (the scheme-adapted presentation of
    /// `node`), each relation checked against its certificate.
    pub fn extract(p: &Presentation, node: &NodeInfo) -> Result<Self, SchemeError> {
        let scheme = scheme_no1()?;
        let layout = layout(scheme, &node.topo).map_err(|e| SchemeError::Mismatch(e.to_string()))?;
        if layout.slots != p.slots {
            return Err(SchemeError::Mismatch(format!(
                "presentation {} is not the scheme's layout",
                p.id.0
            )));
        }
        let generation =
            |error: &dyn fmt::Display| PError::Generation(format!("the IBP rows of presentation {}: {error}", p.id.0));
        let generator = ParametricIbpGenerator::try_new(&p.family).map_err(|e| generation(&e))?;
        let batch = generator.prepare_ordinary_ibp().map_err(|e| generation(&e))?;
        let rows = (0..batch.len()).map(|row| batch.generate(row)).collect();
        let relations = batch.complete(rows).map_err(|e| generation(&e))?.into_relations();
        let context = generator.context().clone();
        let base = p.family.coefficient_context().clone();
        let d = base.parameter("d").ok_or(PError::ContextMismatch)?;
        let builder = Builder {
            context: &context,
            base: &base,
            perm: &layout.perm,
            d,
        };
        let limits = IndexedAlgebraLimits::default();
        // Relations in presentation coordinates and RustRed's sign.
        let mut converted: BTreeMap<String, BTreeMap<Vec<i64>, IndexedCoefficient>> = BTreeMap::new();
        for rule in scheme.rules.iter().filter(|rule| !rule.master && !rule.relation.is_empty()) {
            let mut map = BTreeMap::new();
            for (shift, poly) in &rule.relation {
                map.insert(builder.shift(shift), builder.poly(poly, parity(shift))?);
            }
            converted.insert(rule.name.clone(), map);
        }
        let row_of = |i: usize, j: usize| {
            let wanted = RowId::OrdinaryIbp {
                contraction_momentum: j,
                differentiated_loop: i,
            };
            relations.iter().find(|relation| *relation.row_id() == wanted)
        };
        let mut verified: BTreeMap<String, bool> = BTreeMap::new();
        for name in &scheme.verify_order {
            let rule = (scheme.rules.iter())
                .find(|rule| &rule.name == name)
                .ok_or_else(|| PError::MalformedLibrary(format!("scheme rule {name}")))?;
            let Some(certificate) = &rule.certificate else {
                continue;
            };
            let fixed: Vec<(usize, i64)> = (rule.pattern.iter().enumerate())
                .filter_map(|(a, cond)| cond.fixed().map(|v| (layout.perm[a], v)))
                .collect();
            let restrict = |value: &IndexedCoefficient| -> Result<IndexedCoefficient, PError> {
                if fixed.is_empty() {
                    return Ok(value.clone());
                }
                Ok(context
                    .specialize_fixed_indices(value, &fixed, limits)
                    .map_err(indexed)?
                    .0)
            };
            let mut sum: BTreeMap<Vec<i64>, IndexedCoefficient> = BTreeMap::new();
            let mut ok = true;
            for (generator, offset, weight) in certificate {
                let t = builder.shift(offset);
                let lambda = builder.poly(weight, parity(offset))?;
                let entries: Vec<(Vec<i64>, IndexedCoefficient)> = match generator {
                    Generator::Row(i, j) => match row_of(*i, *j) {
                        Some(relation) => (relation.terms().iter())
                            .map(|(shift, value)| (shift.values().to_vec(), value.clone()))
                            .collect(),
                        None => {
                            ok = false;
                            break;
                        }
                    },
                    Generator::Rule(other) => {
                        // A verified rule, used only where its own domain holds:
                        // the rule's domain shifted by `t` lies inside it.
                        let inside = (scheme.rules.iter())
                            .find(|g| &g.name == other)
                            .is_some_and(|g| {
                                (rule.pattern.iter().zip(&g.pattern).zip(offset))
                                    .all(|((&mine, &theirs), &t)| mine.shifted_inside(t, theirs))
                            });
                        if verified.get(other) != Some(&true) || !inside {
                            ok = false;
                            break;
                        }
                        (converted[other].iter())
                            .map(|(shift, value)| (shift.clone(), value.clone()))
                            .collect()
                    }
                };
                for (sigma, value) in entries {
                    let moved = context.translate(&value, &t, limits).map_err(indexed)?;
                    let product = context.mul(&lambda, &moved).map_err(indexed)?;
                    let product = restrict(&product)?;
                    let at: Vec<i64> = sigma.iter().zip(&t).map(|(a, b)| a + b).collect();
                    let entry = sum.entry(at).or_insert_with(|| context.zero());
                    *entry = context.add(entry, &product).map_err(indexed)?;
                }
            }
            if ok {
                sum.retain(|_, value| !value.is_zero());
                let mut target = BTreeMap::new();
                for (shift, value) in &converted[name] {
                    let value = restrict(value)?;
                    if !value.is_zero() {
                        target.insert(shift.clone(), value);
                    }
                }
                ok = sum.len() == target.len()
                    && sum.iter().all(|(shift, value)| {
                        target.get(shift).is_some_and(|other| {
                            context.sub(value, other).is_ok_and(|diff| diff.is_zero())
                        })
                    });
            }
            verified.insert(name.clone(), ok);
        }
        let mut rules = Vec::with_capacity(scheme.rules.len());
        for rule in &scheme.rules {
            let mut pattern = vec![Cond { lo: i64::MIN, hi: i64::MAX }; layout.perm.len()];
            for (a, &cond) in rule.pattern.iter().enumerate() {
                pattern[layout.perm[a]] = cond;
            }
            let mut terms = Vec::new();
            let mut raw = Vec::new();
            if !rule.master && rule.relation.is_empty() {
                for (shift, num, dens) in &rule.raw {
                    let mut factors = Vec::with_capacity(dens.len());
                    for (den, power) in dens {
                        factors.push((builder.poly(den, 1)?, *power));
                    }
                    raw.push((builder.shift(shift), builder.poly(num, parity(shift))?, factors));
                }
            } else if !rule.master {
                let map = &converted[&rule.name];
                let zero = vec![0_i64; layout.perm.len()];
                let pivot = map.get(&zero).ok_or_else(|| {
                    SchemeError::Mismatch(format!("rule {} has no zero-shift entry", rule.name))
                })?;
                terms.push((zero.clone(), pivot.clone()));
                terms.extend(
                    (map.iter())
                        .filter(|(shift, _)| **shift != zero)
                        .map(|(shift, value)| (shift.clone(), value.clone())),
                );
            }
            rules.push(SchemeRule {
                name: rule.name.clone(),
                pattern,
                master: rule.master,
                terms,
                raw,
                verified: rule.master || verified.get(&rule.name) == Some(&true),
            });
        }
        Ok(Self {
            presentation: p.id,
            context,
            perm: layout.perm,
            rules,
        })
    }

    pub fn rules(&self) -> &[SchemeRule] {
        &self.rules
    }

    pub fn presentation(&self) -> PresentationId {
        self.presentation
    }
}

/// The Scheme program of one owner.
#[derive(Debug)]
pub struct SchemeStep {
    presentation: Arc<Presentation>,
    template: SchemeTemplate,
    lines: usize,
    allow_unverified: bool,
}

impl SchemeStep {
    pub fn new(presentation: Arc<Presentation>, node: &NodeInfo) -> Result<Self, SchemeError> {
        let template = SchemeTemplate::extract(&presentation, node)?;
        let lines = presentation.lines().count();
        let allow_unverified =
            std::env::var("RUSTRED_P_SCHEME_UNVERIFIED").is_ok_and(|value| value == "1");
        Ok(Self {
            presentation,
            template,
            lines,
            allow_unverified,
        })
    }

    pub fn from_owner(library: &PLibrary, owner: &POwnerSpec) -> Result<Self, PError> {
        let LaneRoles::Scheme(_) = owner.roles else {
            return Err(PError::Contract(format!("a scheme step with roles {:?}", owner.roles)));
        };
        if owner.lane != OwnerLane::Scheme || !owner.edge_maps.is_empty() || owner.terminals.len() != 1 {
            return Err(PError::Contract(format!(
                "a scheme step on lane {:?} with {} edge maps and {} terminals",
                owner.lane,
                owner.edge_maps.len(),
                owner.terminals.len()
            )));
        }
        let index = owner
            .node
            .ok_or_else(|| PError::Contract("a scheme owner without a node".to_owned()))?;
        let dag = library
            .topology()
            .ok_or_else(|| PError::Contract("a scheme owner without a topology".to_owned()))?;
        let node = dag
            .nodes
            .get(index.0 as usize)
            .ok_or_else(|| PError::Contract(format!("scheme node {}", index.0)))?;
        Ok(Self::new(Arc::clone(library.presentation(owner.presentation)), node)?)
    }

    pub fn template(&self) -> &SchemeTemplate {
        &self.template
    }

    fn forcer(&self, powers: &[i64], a: usize) -> i64 {
        powers[self.template.perm[a]]
    }

    fn check_key(&self, key: &PKeyView<'_>) -> Result<(), PError> {
        if key.presentation != self.presentation.id || key.powers.len() != self.presentation.slots.len() {
            return Err(PError::Contract(format!(
                "key of presentation {} with {} powers on scheme step {}",
                key.presentation.0,
                key.powers.len(),
                self.presentation.id.0
            )));
        }
        for (slot, &power) in key.powers.iter().enumerate() {
            if slot >= self.lines {
                if power > 0 {
                    return Err(PError::Unsupported(format!("ISP slot {slot} at the positive power {power}")));
                }
            } else if power < 1 {
                return Err(PError::Contract(format!(
                    "line {slot} at power {power} in an Apply key of scheme step {}",
                    self.presentation.id.0
                )));
            }
        }
        Ok(())
    }

    /// Forcer's staging as one order: rank, `-n12`, `-n14`, the line-power sum,
    /// then the loop-2 line order (1, 11, 5, 2, 6, 3, 4, 7, 10, 9, 8).
    fn order(&self, powers: &[i64]) -> Vec<i64> {
        let rank: i64 = powers.iter().filter(|&&p| p < 0).map(|&p| -p).sum();
        let sum: i64 = powers[..self.lines].iter().filter(|&&p| p > 0).sum();
        let mut key = vec![rank, -self.forcer(powers, 11), -self.forcer(powers, 13), sum];
        for a in [1, 11, 5, 2, 6, 3, 4, 7, 10, 9, 8] {
            key.push(self.forcer(powers, a - 1));
        }
        key
    }

    pub fn apply(
        &self,
        cx: Option<&PStepContext<'_>>,
        key: &PKeyView<'_>,
        limits: &ReductionLimits,
    ) -> Result<PStepOut, PError> {
        self.check_key(key)?;
        let rule = (self.template.rules.iter())
            .find(|rule| rule.pattern.iter().zip(key.powers).all(|(c, &n)| c.holds(n)))
            .ok_or_else(|| PError::Unsupported(format!("no scheme rule for {:?}", key.powers)))?;
        if rule.master {
            let terminal = cx
                .and_then(|cx| cx.owner.spec.terminals.first().copied())
                .ok_or_else(|| PError::Contract("the scheme corner without a terminal".to_owned()))?;
            let one = self.presentation.family.coefficient_context().one();
            return Ok(PStepOut {
                terminals: vec![(terminal, key.tag.clone(), one)],
                ..PStepOut::default()
            });
        }
        if !rule.verified && !self.allow_unverified {
            return Err(PError::Unsupported(format!(
                "scheme rule {} has no verified certificate",
                rule.name
            )));
        }
        let ilimits = IndexedAlgebraLimits {
            exact_algebra: limits.exact_algebra,
            ..IndexedAlgebraLimits::default()
        };
        let context = &self.template.context;
        let base = self.presentation.family.coefficient_context();
        if rule.terms.is_empty() {
            return self.apply_raw(rule, key, limits, ilimits);
        }
        let (pivot, _) = context
            .specialize(&rule.terms[0].1, key.powers, ilimits)
            .map_err(indexed)?;
        if pivot.is_zero() {
            return Err(PError::Contract(format!(
                "scheme rule {} has a zero pivot at {:?}",
                rule.name, key.powers
            )));
        }
        let mine = self.order(key.powers);
        let mut children = Vec::with_capacity(rule.terms.len());
        for (shift, value) in &rule.terms[1..] {
            let (value, _) = context.specialize(value, key.powers, ilimits).map_err(indexed)?;
            if value.is_zero() {
                continue;
            }
            let weight = base
                .try_div(&value, &pivot, limits.exact_algebra)
                .and_then(|w| base.try_neg(&w, limits.exact_algebra))
                .map_err(exact)?;
            let powers: Vec<i64> = key.powers.iter().zip(shift).map(|(n, s)| n + s).collect();
            if powers[self.lines..].iter().any(|&p| p > 0) {
                return Err(PError::Contract(format!(
                    "scheme rule {} emits a positive ISP power {powers:?}",
                    rule.name
                )));
            }
            let stage = if powers[..self.lines].iter().any(|&p| p <= 0) {
                PStage::Route
            } else {
                if self.order(&powers) >= mine {
                    return Err(PError::Contract(format!(
                        "scheme rule {} does not descend: {:?} -> {powers:?}",
                        rule.name, key.powers
                    )));
                }
                PStage::Apply
            };
            children.push(PChild {
                stage,
                presentation: self.presentation.id,
                powers,
                tag: key.tag.clone(),
                coefficient: weight,
            });
        }
        Ok(PStepOut {
            children,
            ..PStepOut::default()
        })
    }
}

impl SchemeStep {
    /// A rule without a relation: `c_j = num / Prod den^e` at the key.
    fn apply_raw(
        &self,
        rule: &SchemeRule,
        key: &PKeyView<'_>,
        limits: &ReductionLimits,
        ilimits: IndexedAlgebraLimits,
    ) -> Result<PStepOut, PError> {
        let context = &self.template.context;
        let base = self.presentation.family.coefficient_context();
        let mine = self.order(key.powers);
        let mut children = Vec::with_capacity(rule.raw.len());
        for (shift, num, dens) in &rule.raw {
            let (mut weight, _) = context.specialize(num, key.powers, ilimits).map_err(indexed)?;
            if weight.is_zero() {
                continue;
            }
            for (den, power) in dens {
                let (value, _) = context.specialize(den, key.powers, ilimits).map_err(indexed)?;
                if value.is_zero() {
                    return Err(PError::Contract(format!(
                        "scheme rule {} divides by zero at {:?}",
                        rule.name, key.powers
                    )));
                }
                for _ in 0..*power {
                    weight = base.try_div(&weight, &value, limits.exact_algebra).map_err(exact)?;
                }
            }
            let powers: Vec<i64> = key.powers.iter().zip(shift).map(|(n, s)| n + s).collect();
            if powers[self.lines..].iter().any(|&p| p > 0) {
                return Err(PError::Contract(format!(
                    "scheme rule {} emits a positive ISP power {powers:?}",
                    rule.name
                )));
            }
            let stage = if powers[..self.lines].iter().any(|&p| p <= 0) {
                PStage::Route
            } else {
                if self.order(&powers) >= mine {
                    return Err(PError::Contract(format!(
                        "scheme rule {} does not descend: {:?} -> {powers:?}",
                        rule.name, key.powers
                    )));
                }
                PStage::Apply
            };
            children.push(PChild {
                stage,
                presentation: self.presentation.id,
                powers,
                tag: key.tag.clone(),
                coefficient: weight,
            });
        }
        Ok(PStepOut {
            children,
            ..PStepOut::default()
        })
    }
}

impl PLaneStep for SchemeStep {
    fn lane(&self) -> OwnerLane {
        OwnerLane::Scheme
    }

    fn step(&self, cx: &PStepContext<'_>, key: &PKeyView<'_>) -> Result<PStepOut, PError> {
        self.apply(Some(cx), key, cx.limits)
    }

    fn order_key(&self, _cx: &PStepContext<'_>, powers: &[i64]) -> Result<POrderKey, PError> {
        if powers.len() != self.presentation.slots.len() {
            return Err(PError::Contract("scheme order key arity".to_owned()));
        }
        Ok(POrderKey::Lexicographic(self.order(powers)))
    }
}
