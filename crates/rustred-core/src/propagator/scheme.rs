#[derive(Clone, Debug, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
enum OrderRow {
    /// `Sum max(0, -n)` over every slot: the numerator rank.
    Rank,
    /// `Sum max(0, n)` over the lines.
    LineSum,
    /// `Sum w_a n_a` in Forcer's slot order; with `when`, only in that numerator
    /// regime (`rank_positive` or `rank_zero`) and 0 in the other. Keys compared
    /// at such a row have equal rank (the first row must be `rank`), so they are
    /// in the same regime: Forcer's loop 1 (numerators left) and loop 2 (none).
    Linear {
        weights: Vec<i64>,
        #[serde(default)]
        when: Option<Regime>,
    },
}

#[derive(Clone, Copy, Debug, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
enum Regime {
    RankPositive,
    RankZero,
}

