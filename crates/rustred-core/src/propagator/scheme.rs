#[derive(Debug)]
pub enum SchemeError {
    Mismatch(String),
    Failure(PError),
}

impl fmt::Display for SchemeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Mismatch(reason) => write!(f, "scheme template: {reason}"),
            Self::Failure(error) => error.fmt(f),
        }
    }
}

impl From<PError> for SchemeError {
    fn from(error: PError) -> Self {
        Self::Failure(error)
    }
}

impl From<SchemeError> for PError {
    fn from(error: SchemeError) -> Self {
        match error {
            SchemeError::Mismatch(reason) => PError::Contract(format!("scheme template: {reason}")),
            SchemeError::Failure(error) => error,
        }
    }
}

