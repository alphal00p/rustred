/// Compact coordinates are intentionally coefficient-free.  An exact
/// coefficient and complete provenance are regenerated by `replay_path`.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct FourLoopNextCompactPath {
    packed: u64,
}

const PATH_BRANCH_BITS: u32 = 7;
const PATH_TERM_BITS: u32 = 7;
const PATH_DEPTH_BITS: u32 = 2;
const PATH_LEAF_BITS: u32 = 20;
const PATH_USED_BITS: u32 =
    3 * PATH_BRANCH_BITS + PATH_DEPTH_BITS + PATH_TERM_BITS + PATH_LEAF_BITS;
const PATH_BRANCH_MASK: u64 = (1 << PATH_BRANCH_BITS) - 1;
const PATH_TERM_MASK: u64 = (1 << PATH_TERM_BITS) - 1;
const PATH_DEPTH_MASK: u64 = (1 << PATH_DEPTH_BITS) - 1;
const PATH_LEAF_MASK: u64 = (1 << PATH_LEAF_BITS) - 1;
const _: () = assert!(size_of::<FourLoopNextCompactPath>() == 8);
const _: () = assert!(111 < (1 << PATH_TERM_BITS));
const _: () = assert!(66 < (1 << PATH_BRANCH_BITS));
const _: () = assert!(11 < (1 << PATH_BRANCH_BITS));
const _: () = assert!(FOUR_LOOP_NEXT_INVENTORY_FULL_POWER_KEY_BOUND < (1 << PATH_LEAF_BITS));
const _: () = assert!(FOUR_LOOP_NEXT_INVENTORY_ROW_PATH_BOUND < (1 << 17));
const _: () = assert!(FOUR_LOOP_NEXT_INVENTORY_RAW_ROWS < (1 << 11));

impl fmt::Debug for FourLoopNextCompactPath {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("FourLoopNextCompactPath")
            .field("raw_term_index", &self.raw_term_index())
            .field("root_branch_index", &self.root_branch_index())
            .field("recursive_depth", &self.recursive_depth())
            .field("recursive_branch_indices", &self.recursive_branch_indices())
            .field("leaf_id", &self.leaf_id())
            .finish()
    }
}

impl FourLoopNextCompactPath {
    fn validate_encoding(self) -> Result<(), FourLoopNextInventoryError> {
        let depth = usize::from(self.recursive_depth());
        if self.packed >> PATH_USED_BITS != 0
            || depth > RECURSIVE_BRANCH_SLOTS
            || self.recursive_branch_indices()[depth..]
                .iter()
                .any(|&index| index != 0)
        {
            return Err(FourLoopNextInventoryError::NonCanonicalPathEncoding);
        }
        Ok(())
    }

    pub const fn raw_term_index(self) -> u16 {
        ((self.packed >> (3 * PATH_BRANCH_BITS + PATH_DEPTH_BITS)) & PATH_TERM_MASK) as u16
    }

    pub const fn root_branch_index(self) -> u8 {
        (self.packed & PATH_BRANCH_MASK) as u8
    }

    /// Number of dynamically regenerated polynomial maps.  Strict-mask depth
    /// additionally includes the initial strict root branch.
    pub const fn recursive_depth(self) -> u8 {
        ((self.packed >> (3 * PATH_BRANCH_BITS)) & PATH_DEPTH_MASK) as u8
    }

    pub const fn recursive_branch_indices(self) -> [u8; RECURSIVE_BRANCH_SLOTS] {
        [
            ((self.packed >> PATH_BRANCH_BITS) & PATH_BRANCH_MASK) as u8,
            ((self.packed >> (2 * PATH_BRANCH_BITS)) & PATH_BRANCH_MASK) as u8,
        ]
    }

    pub const fn leaf_id(self) -> u32 {
        ((self.packed >> (3 * PATH_BRANCH_BITS + PATH_DEPTH_BITS + PATH_TERM_BITS))
            & PATH_LEAF_MASK) as u32
    }

    fn new(
        raw_term_index: usize,
        root_branch_index: usize,
        recursive_depth: usize,
        recursive_branch_indices: [u8; RECURSIVE_BRANCH_SLOTS],
        leaf_id: u32,
    ) -> Result<Self, FourLoopNextInventoryError> {
        if raw_term_index > PATH_TERM_MASK as usize {
            return Err(FourLoopNextInventoryError::CoordinateOverflow {
                coordinate: "raw term index",
                requested: raw_term_index as u128,
                limit: PATH_TERM_MASK as u128,
            });
        }
        let raw_term_index = raw_term_index as u8;
        if root_branch_index > PATH_BRANCH_MASK as usize {
            return Err(FourLoopNextInventoryError::CoordinateOverflow {
                coordinate: "root branch index",
                requested: root_branch_index as u128,
                limit: PATH_BRANCH_MASK as u128,
            });
        }
        let root_branch_index = root_branch_index as u8;
        let recursive_depth = u8::try_from(recursive_depth).map_err(|_| {
            FourLoopNextInventoryError::CoordinateOverflow {
                coordinate: "recursive map depth",
                requested: recursive_depth as u128,
                limit: RECURSIVE_BRANCH_SLOTS as u128,
            }
        })?;
        if usize::from(recursive_depth) > RECURSIVE_BRANCH_SLOTS
            || recursive_branch_indices[usize::from(recursive_depth)..]
                .iter()
                .any(|&index| index != 0)
        {
            return Err(FourLoopNextInventoryError::NonCanonicalPathEncoding);
        }
        if u64::from(leaf_id) > PATH_LEAF_MASK {
            return Err(FourLoopNextInventoryError::CoordinateOverflow {
                coordinate: "leaf id",
                requested: u64::from(leaf_id) as u128,
                limit: PATH_LEAF_MASK as u128,
            });
        }
        if let Some(&index) = recursive_branch_indices
            .iter()
            .find(|&&index| u64::from(index) > PATH_BRANCH_MASK)
        {
            return Err(FourLoopNextInventoryError::CoordinateOverflow {
                coordinate: "recursive branch index",
                requested: u128::from(index),
                limit: PATH_BRANCH_MASK as u128,
            });
        }
        let packed = u64::from(root_branch_index)
            | (u64::from(recursive_branch_indices[0]) << PATH_BRANCH_BITS)
            | (u64::from(recursive_branch_indices[1]) << (2 * PATH_BRANCH_BITS))
            | (u64::from(recursive_depth) << (3 * PATH_BRANCH_BITS))
            | (u64::from(raw_term_index) << (3 * PATH_BRANCH_BITS + PATH_DEPTH_BITS))
            | (u64::from(leaf_id) << (3 * PATH_BRANCH_BITS + PATH_DEPTH_BITS + PATH_TERM_BITS));
        Ok(Self { packed })
    }

    #[doc(hidden)]
    pub fn with_leaf_id_for_replay(self, leaf_id: u32) -> Self {
        let shift = 3 * PATH_BRANCH_BITS + PATH_DEPTH_BITS + PATH_TERM_BITS;
        Self {
            packed: (self.packed & !(PATH_LEAF_MASK << shift))
                | ((u64::from(leaf_id) & PATH_LEAF_MASK) << shift),
        }
    }

    #[doc(hidden)]
    pub fn with_root_branch_for_replay(self, root_branch_index: u8) -> Self {
        Self {
            packed: (self.packed & !PATH_BRANCH_MASK)
                | (u64::from(root_branch_index) & PATH_BRANCH_MASK),
        }
    }

    #[doc(hidden)]
    pub fn with_recursive_branch_for_replay(self, depth: usize, branch: u8) -> Self {
        let mut result = self;
        if depth < RECURSIVE_BRANCH_SLOTS {
            let shift = (depth as u32 + 1) * PATH_BRANCH_BITS;
            result.packed = (result.packed & !(PATH_BRANCH_MASK << shift))
                | ((u64::from(branch) & PATH_BRANCH_MASK) << shift);
        }
        result
    }

    #[doc(hidden)]
    pub fn with_raw_term_index_for_replay(self, raw_term_index: u16) -> Self {
        let shift = 3 * PATH_BRANCH_BITS + PATH_DEPTH_BITS;
        Self {
            packed: (self.packed & !(PATH_TERM_MASK << shift))
                | ((u64::from(raw_term_index) & PATH_TERM_MASK) << shift),
        }
    }

    #[doc(hidden)]
    pub fn with_recursive_depth_for_replay(self, recursive_depth: u8) -> Self {
        let shift = 3 * PATH_BRANCH_BITS;
        Self {
            packed: (self.packed & !(PATH_DEPTH_MASK << shift))
                | ((u64::from(recursive_depth) & PATH_DEPTH_MASK) << shift),
        }
    }

    #[doc(hidden)]
    pub fn with_reserved_bit_for_replay(self) -> Self {
        Self {
            packed: self.packed | (1_u64 << 63),
        }
    }
}

