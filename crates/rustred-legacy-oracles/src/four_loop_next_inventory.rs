#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FourLoopNextBoundaryOccurrence {
    packed: u32,
}

impl FourLoopNextBoundaryOccurrence {
    const PATH_BITS: u32 = 17;
    const PATH_MASK: u32 = (1 << Self::PATH_BITS) - 1;

    fn new(row_index: usize, path_index: usize) -> Result<Self, FourLoopNextInventoryError> {
        if row_index >= (1 << 11) {
            return Err(FourLoopNextInventoryError::CoordinateOverflow {
                coordinate: "boundary occurrence row",
                requested: row_index as u128,
                limit: ((1 << 11) - 1) as u128,
            });
        }
        if path_index >= (1 << Self::PATH_BITS) {
            return Err(FourLoopNextInventoryError::CoordinateOverflow {
                coordinate: "boundary occurrence path",
                requested: path_index as u128,
                limit: Self::PATH_MASK as u128,
            });
        }
        Ok(Self {
            packed: ((row_index as u32) << Self::PATH_BITS) | path_index as u32,
        })
    }

    pub const fn row_index(self) -> u16 {
        (self.packed >> Self::PATH_BITS) as u16
    }

    pub const fn path_index(self) -> u32 {
        self.packed & Self::PATH_MASK
    }
}

