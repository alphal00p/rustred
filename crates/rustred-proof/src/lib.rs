//! rustred-proof: proof kernels for stored IBP rules (lane proof-kernel, 2026-11-13).
//!
//! Three modes, one record per rule (JSON line):
//! * `streaming-eval` ([`stream::run_stored`]): one streaming pass over the coefficient texts evaluates every stored
//!   weight and rhs coefficient at k hash-derived points (mod p and exact over Z) and accumulates the column sums
//!   `sum_j w_j a_jc + r_c - delta_c`; memory columns x k. Verdict `PASS_PROBABILISTIC` + error bound, or `FAIL`
//!   (a certain disproof). Never claims exactness.
//! * `instance-exact` (same entry point): per integer key, B_d + 1 exact evaluations in d prove every column identity
//!   EXACTLY at that key (`EXACT_PROVED_AT_KEY`); hidden / irregular / exception / not-in-case keys are classified.
//! * `instance-span` ([`span::run_span`]): WEIGHT-FREE. Per integer key, the rule vector is tested for membership in
//!   the span over Q(d) of the IBP rows of the rule's recorded seed set at that key: modular solves at hash-derived
//!   (prime, d) points, rational reconstruction of the weights in d, then an EXACT check `W A = L T v` in Z[d]
//!   (`EXACT_IN_SPAN_AT_KEY`). Affine cases are handled at the key (equations hold or `NOT_IN_CASE`).
//!
//! The arithmetic core is std only (own SHA-256, bigint, Montgomery) so that the kernel can be compiled and tested
//! with plain `rustc` as well; with feature `engine` the IBP rows are generated by RustRed itself
//! ([`engine`]: `rustred::solver::SourceSystem::from_family_with_capacity`, as `rr_node` does) and compared with the
//! rows stored in a certificate. The H8 kernel (handoff/helper-h10-kernel) is the origin of `core` and `stream`.
