/// Run `f`, turning a kernel refusal (`core::die`) or any other panic into `Err(message)`.
pub fn guarded<T>(f: impl FnOnce() -> T) -> Result<T, String> {
    let prev = std::panic::take_hook();
    std::panic::set_hook(Box::new(|_| {}));
    let r = std::panic::catch_unwind(std::panic::AssertUnwindSafe(f));
    std::panic::set_hook(prev);
    r.map_err(|e| {
        if let Some(k) = e.downcast_ref::<core::KernelError>() {
            k.0.clone()
        } else if let Some(s) = e.downcast_ref::<String>() {
            format!("panic: {}", s)
        } else if let Some(s) = e.downcast_ref::<&str>() {
            format!("panic: {}", s)
        } else {
            "panic".into()
        }
    })
}

/// Record for a refused / failed run.
pub fn error_record(msg: &str) -> String {
    let verdict = if msg.starts_with("UNSUPPORTED") {
        "UNSUPPORTED"
    } else if msg.starts_with("MISSING_CERT_RULE") {
        "MISSING_CERT_RULE"
    } else {
        "ERROR"
    };
    format!(
        "{{\"verdict\":{},\"error\":{}}}",
        core::jstr(verdict),
        core::jstr(msg)
    )
}
